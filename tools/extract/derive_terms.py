"""Collect acronym candidates from the extracted chapters.

Dev-only tool. It is not part of the app.

    tools/extract/.venv/bin/python -I tools/extract/derive_terms.py

Writes two files for each certification in sources-text/derived/ (A+, Network+, and Security+ are kept apart):
- a-plus-acronyms.md, network-plus-acronyms.md, security-plus-acronyms.md: the official acronym lists (A+ merges 220-1201 and
  220-1202), with notes where the lists differ or no book uses an acronym. The main source for content/acronyms/.
- acronym-candidates.md, network-plus-acronym-candidates.md, security-plus-acronym-candidates.md: "Expanded Form (ACRONYM)"
  pairs found in the book chapters.
"""

import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEXT = ROOT / "sources-text"
OUT = TEXT / "derived"

PAIR = re.compile(r"((?:[A-Za-z0-9][\w'’/-]*[ -]){1,9}?)\(([A-Z][A-Za-z0-9/&.+-]{1,9})\)")
SMALL = {"of", "and", "the", "for", "to", "in", "on", "over", "a", "an", "as", "with", "by", "at", "or"}


def initials_match(words, acr):
    """True when the acronym letters follow the start letters of the words."""
    letters = [c for c in acr.lower() if c.isalpha()]
    if len(letters) < 2:
        return False
    # Take the shortest tail of the words whose initials (and inner capitals) cover the acronym.
    for start in range(len(words) - 1, -1, -1):
        tail = words[start:]
        if tail[0].lower() in SMALL:
            continue
        pool = "".join(w[0].lower() + "".join(c.lower() for c in w[1:] if c.isupper() or c.isdigit())
                       for w in tail if w.lower() not in SMALL or len(tail) == 1)
        full = " ".join(tail).lower()
        i = 0
        for c in pool:
            if i < len(letters) and c == letters[i]:
                i += 1
        if i == len(letters) and tail[0][0].lower() == letters[0]:
            return " ".join(tail)
        if len(" ".join(tail)) > 80:
            break
        _ = full
    return False


CERTS = {  # certification: (source categories, {exam: official objectives folder}, official file, candidates file, name)
    "a-plus": (["general", "core1", "core2"],
               {"Core 1": "general/objectives-220-1201", "Core 2": "general/objectives-220-1202"},
               "a-plus-acronyms.md", "acronym-candidates.md", "A+"),
    "network-plus": (["network"], {"Network+": "network/objectives-n10-009"},
                     "network-plus-acronyms.md", "network-plus-acronym-candidates.md", "Network+"),
    "security-plus": (["sec"], {"Security+": "sec/objectives-sy0-801"},
                      "security-plus-acronyms.md", "security-plus-acronym-candidates.md", "Security+"),
}


def official_acronyms(official):
    """{acronym: {exam: expanded form}} from the official objectives acronym lists."""
    out = defaultdict(dict)
    for core, folder in official.items():
        for md in (TEXT / folder).glob("*acronym-list.md"):
            for acr, exp in re.findall(r"^\| (?!Acronym |---)([^|]+?) \| ([^|]+?) \|$", md.read_text(encoding="utf-8"), re.M):
                out[acr][core] = exp
    return out


def write_official(official, book_text, out_name, cert_name, folders):
    rows = []
    for acr in sorted(official, key=str.lower):
        forms = official[acr]
        cores = " and ".join(sorted(forms))
        uniq = sorted(set(forms.values()), key=lambda e: (e.lower(), e))
        note = ""
        if len(uniq) > 1:
            note = "The lists differ: " + "; ".join(f"{c}: {e}" for c, e in sorted(forms.items())) + ". Check which is correct."
        if not re.search(r"(?<![\w-])" + re.escape(acr) + r"(?![\w-])", book_text):
            note = (note + " " if note else "") + "Not used in the books."
        rows.append(f"| {acr} | {uniq[0] if len(uniq) == 1 else ' / '.join(uniq)} | {cores} | {note} |")
    head = (f"# {cert_name} acronyms (official)\n\n"
            f"Generated by `tools/extract/derive_terms.py` from the official acronym lists in "
            f"{', '.join(f'`{f}/`' for f in folders)}. This is the main source for `content/acronyms/` "
            f"({cert_name} records). The notes flag rows where the exam lists differ and acronyms that no book uses.\n\n"
            "| Acronym | Expanded form | Exam lists | Notes |\n|---|---|---|---|\n")
    (OUT / out_name).write_text(head + "\n".join(rows) + "\n", encoding="utf-8")
    return len(rows)


def main():
    OUT.mkdir(exist_ok=True)
    for cert, (cats, official_dirs, official_name, cand_name, cert_name) in CERTS.items():
        found = defaultdict(lambda: defaultdict(set))  # acr -> expansion -> books
        book_text = []
        for cat in cats:
            for md in (TEXT / cat).glob("*/*.md"):
                book = md.parent.name
                if book.startswith("objectives-"):
                    continue
                text = re.sub(r"[*`]", "", md.read_text(encoding="utf-8"))
                book_text.append(text)
                for m in PAIR.finditer(text):
                    words = re.split(r"[ -]+", m.group(1).strip())
                    acr = m.group(2).rstrip(".")
                    exp = initials_match(words, acr)
                    if exp:
                        exp = re.sub(r"\s+", " ", exp).strip()
                        found[acr][exp[0].upper() + exp[1:]].add(book)
        official = official_acronyms(official_dirs)
        n_official = write_official(official, "\n".join(book_text), official_name, cert_name, list(official_dirs.values()))
        rows = []
        for acr in sorted(found, key=str.lower):
            # Merge expansions that differ only by case.
            merged = defaultdict(set)
            for e, books in found[acr].items():
                key = next((k for k in merged if k.lower() == e.lower()), e)
                merged[key] |= books
            for e, books in sorted(merged.items(), key=lambda x: -len(x[1])):
                rows.append(f"| {acr} | {e} | {'yes' if acr in official else ''} | {', '.join(sorted(books))} |")
        head = (f"# {cert_name} acronym candidates\n\n"
                "Generated by `tools/extract/derive_terms.py` from the extracted chapters. "
                "Each row is an acronym, an expanded form found in the text, whether the acronym is on the official "
                f"list (`{official_name}`), and the books that use it. Use the official list first; "
                "the other rows are extra terms the books use. Some rows are noise.\n\n"
                "| Acronym | Expanded form | Official | Books |\n|---|---|---|---|\n")
        (OUT / cand_name).write_text(head + "\n".join(rows) + "\n", encoding="utf-8")
        print(f"{cert}: {n_official} official acronyms; {len(found)} book acronyms, {len(rows)} rows")


if __name__ == "__main__":
    main()
